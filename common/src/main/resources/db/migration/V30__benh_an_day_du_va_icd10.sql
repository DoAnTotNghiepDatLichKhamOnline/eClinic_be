-- =====================================================================
-- Hồ sơ bệnh án đầy đủ hơn + danh mục ICD-10 (DOANTOTNGH-11, phase 3)
--  * icd10: danh mục chỉ đọc, gồm các mã hay gặp ở phòng khám ngoại trú (tên tiếng Việt theo bản ICD-10 của Bộ Y tế,
--    tiếng Anh theo WHO). Bác sĩ chọn 1 mã cho chẩn đoán chính (không bắt buộc); chẩn đoán vẫn là chữ tự do.
--  * icd10.man_tinh: mã thuộc 1 mục của Phụ lục VII Thông tư 26/2025/TT-BYT (252 bệnh được kê đơn ngoại trú trên 30
--    ngày; đái tháo đường trừ các mã .0, .1). Chẩn đoán chính mạn tính thì mỗi thuốc được kê tối đa 90 ngày, không thì 30
--    (kiểm tra trong service).
--  * ho_so_benh_an: lý do khám, sinh hiệu, khám lâm sàng, mã ICD chẩn đoán chính, chẩn đoán kèm theo. Đều không bắt
--    buộc; hồ sơ cũ để trống. Trẻ dưới 72 tháng có kê thuốc thì phải có cân nặng (kiểm tra trong service).
--  * chi_tiet_don_thuoc.so_luong: tổng số lượng cấp theo đơn vị của thuốc. Dòng mới / dòng sửa bắt buộc gửi so_luong và
--    so_ngay_dung (kiểm tra ở request); dòng cũ để trống tới khi hồ sơ được sửa.
-- =====================================================================
CREATE TABLE icd10
(
    ma       VARCHAR(10)  NOT NULL COMMENT 'mã ICD-10 có dấu chấm, vd J06.9',
    ten      VARCHAR(255) NOT NULL,
    ten_en   VARCHAR(255) NOT NULL,
    man_tinh BOOLEAN      NOT NULL DEFAULT FALSE COMMENT 'thuộc Phụ lục VII TT 26/2025: kê đơn tối đa 90 ngày',
    CONSTRAINT pk_icd10 PRIMARY KEY (ma)
);

ALTER TABLE ho_so_benh_an
    ADD COLUMN ly_do_kham          TEXT         NULL COMMENT 'lý do khám, triệu chứng' AFTER id_bac_si,
    ADD COLUMN mach                INT          NULL COMMENT 'lần/phút' AFTER ly_do_kham,
    ADD COLUMN nhiet_do            DECIMAL(3, 1) NULL COMMENT '°C' AFTER mach,
    ADD COLUMN huyet_ap_tam_thu    INT          NULL COMMENT 'mmHg' AFTER nhiet_do,
    ADD COLUMN huyet_ap_tam_truong INT          NULL COMMENT 'mmHg' AFTER huyet_ap_tam_thu,
    ADD COLUMN nhip_tho            INT          NULL COMMENT 'lần/phút' AFTER huyet_ap_tam_truong,
    ADD COLUMN can_nang            DECIMAL(5, 2) NULL COMMENT 'kg' AFTER nhip_tho,
    ADD COLUMN chieu_cao           DECIMAL(4, 1) NULL COMMENT 'cm' AFTER can_nang,
    ADD COLUMN kham_lam_sang       TEXT         NULL COMMENT 'kết quả khám lâm sàng' AFTER chieu_cao,
    ADD COLUMN ma_icd_chinh        VARCHAR(10)  NULL COMMENT 'mã ICD-10 của chẩn đoán chính' AFTER chan_doan,
    ADD COLUMN chan_doan_kem_theo  TEXT         NULL COMMENT 'các bệnh kèm theo, chữ tự do' AFTER ma_icd_chinh,
    ADD CONSTRAINT fk_ho_so_benh_an_icd10 FOREIGN KEY (ma_icd_chinh) REFERENCES icd10 (ma);

ALTER TABLE chi_tiet_don_thuoc
    ADD COLUMN so_luong INT NULL COMMENT 'tổng số lượng cấp, theo đơn vị của thuốc' AFTER so_ngay_dung,
    ADD CONSTRAINT ck_chi_tiet_don_thuoc_so_luong CHECK (so_luong IS NULL OR so_luong > 0);

